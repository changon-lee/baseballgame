function build(t) {
  return {
    id: t.id, name: t.name, short: t.short, colors: t.colors,
    batters: t.batters.map(([name, pos, bats, power, contact, eye, num], i) => ({
      id: `${t.id}-b${String(i + 1).padStart(2, '0')}`, name, pos, bats, power, contact, eye, num: num ?? null,
    })),
    pitchers: t.pitchers.map(([name, throws, role, velo, control, stamina, pitches, num], i) => ({
      id: `${t.id}-p${String(i + 1).padStart(2, '0')}`, name, throws, role, velo, control, stamina,
      pitches: pitches.split(' '), num: num ?? null,
    })),
  };
}

export const TEAMS = RAW.map(build);
export const USER_TEAM_ID = 'samsung';
export function getTeam(id) { return TEAMS.find(t => t.id === id); }
